def in092u_bytes(
    cut: str = "06-nov-2026 09:48:14",
    rows: list[tuple[str, str, str]] | None = None,
    excludes_zero: bool = True,
) -> bytes:
    lines = [
        f"IN092U        Inventory by Stockroom        {cut}        Page: 1",
        "Excludes Zero Physical Quantity" if excludes_zero else "All quantities",
        "Item                 Stockroom     Physical Quantity        Value",
        "-" * 70,
    ]
    for item, room, qty in rows if rows is not None else IN_ROWS:
        lines.append(f"{item:<20} {room:<4} {qty:>18} {'12.50':>14}")
    lines.append("*** End of report ***")
    return ("\r\n".join(lines) + "\r\n").encode("cp850")


